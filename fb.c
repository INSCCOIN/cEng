void text(int x, int y, const char *s, uint16_t c)
{
    while (*s) {
        unsigned char ch = (unsigned char)*s++;
        int gx, gy;
        if (ch < 32 || ch > 126)
            ch = '?';
        for (gx = 0; gx < 5; gx++) {
            unsigned char col = FONT[ch - 32][gx];
            for (gy = 0; gy < 7; gy++)
                if (col & (1 << gy))
                    px(x + gx, y + gy, c);
        }
        x += 6;
    }
}
